from typing import TypedDict, Literal, Any
from dataclasses import dataclass

class PasswordProfileJson(TypedDict):
    forceChangePasswordNextSignIn: bool
    password: str

type UserType = Literal["member", "guest"]

class CreateUserJson(TypedDict):
    # The status of the account. Can be true or false.
    accountEnabled: bool

    # The name in displayed in the directory. This is the full name of the user.
    displayName: str

    # The mail alias of the user. This should be `user` of `user@domain.com`, as it is by default.
    mailNickname: str

    # The "email" of the user, or the principal name. For example, `user@domain.com`.
    userPrincipalName: str

    # The type of user, this is either Member or Guest. This will be a setting to enable
    # in the options. It will apply to every user being created.
    userType: UserType

    # The password profile of the user.
    passwordProfile: PasswordProfileJson

    # The first name of the user.
    givenName: str

    # The last name of the user.
    surname: str

@dataclass
class RequestErrorResponse:
    '''A class representing the error response of a Graph request.'''
    code: str = ""
    message: str = ""
    date: str = ""
    request_id: str = ""
    # The property field of the Graph User that failed.
    target: str = ""
    status_code: int = -1

    def format_error(self) -> str:
        '''Returns a client-safe error code formatted into a string from the error data.'''
        l_code: str = self.code.lower()
        l_target: str = self.target.lower() if self.target != "" else "unknownTarget"

        error_map: dict[tuple[str, str], str] = {
            ("invalidvalue", "userprincipalname"): "Invalid UPN domain",
            ("objectconflict", "userprincipalname"): "UPN already exists",
            ("invalidauthenticationtoken", ""): "Token is invalid",
        }

        tup_key = (l_code, l_target)
        default_error: str = f"An unknown error occurred (see application logs for details)"

        err: str | None = error_map.get(tup_key, None)
        # handles 429 errors only.
        if self.status_code == 429:
            err = f"Max retry attempt failed (429 status code)"
        elif err is None:
            err = default_error
        else:
            err = f"{err} ({self.target})"
        
        return err

