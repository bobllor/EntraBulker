class GraphAccountCacheReader(TypedDict):
    # A list of dictionary objects which are the accounts. The dictionary of
    # the list is used to authenticate silently.
    #
    # The dictionary schema is generated by MSAL, and the only key that will
    # be used is the `username` key.
    #
    # If for whatever reason the `username` key does not exist, then it will use
    # the last value in the cache as a fallback.
    account_cache: list[dict[str, Any]]

    # The most recent account login. This is the username/principal name,
    # for example: `user@domain.com`. This is used to get the most recent
    # user if multiple users exist in the cache.
    recent_username: str

class FailedUserObject(TypedDict):
    '''Used in GraphError to represent a failed user.'''
    name: str
    # The error message. This will be displayed after the name,
    # for example: John Doe: An error (target).
    error: str

class GraphError(TypedDict):
    '''Represents an error object from Graph. This is used in the front end and
    *should not be logged* due to the usernames.
    '''
    # The time of the failure in seconds.
    timestamp: str
    total_users_count: int
    failed_users_count: int
    # Users that failed to get created.
    failed_users: list[FailedUserObject]

@dataclass
class GraphBatchPostUserInfo:
    '''An object holding information of the batch responses from batch requests.'''
    # A list of created users. This must be their display name only.
    created_users: list[str]
    # A list of failed users. This must be their display name only.
    failed_users: list[str]
    # A list of users to retry, this will be used to recreate the batch information.
    retry_users: list[CreateUserJson]
    graph_error: GraphError
    # The amount of failed parses of the batch response. This is only used for exceptions, and
    # does not represent the batch response contents itself.
    failed_parses: int = 0
    # The retry time. It is the maximum amount of time used given by the Retry-After header
    # in any of the responses. Only used if retry_users has at least one user.
    retry_time: int = 0

class BatchRequest(TypedDict):
    '''A request inside a BatchBody.'''
    id: str
    method: str
    url: str
    body: Any
    headers: dict[str, str]

class BatchBody(TypedDict):
    '''A batch body request for batching Graph requests.'''
    # An array of requests to send to the batch endpoint. There can only
    # be a maximum of 20 requests per request.
    requests: list[BatchRequest]

class BatchResponse(TypedDict):
    responses: list[dict[str, Any]]